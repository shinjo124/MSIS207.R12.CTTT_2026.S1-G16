import assert from 'node:assert/strict';
import test from 'node:test';
import { DatabaseSync } from 'node:sqlite';
import { once } from 'node:events';
import express from 'express';
import { pool } from '../src/db/pool.js';

test('an owner can create, edit and delete with one connection; another fixture user cannot read or edit', async (t) => {
  let viewer = 'alice';
  const previousWeatherKey = process.env.OPENWEATHER_API_KEY;
  delete process.env.OPENWEATHER_API_KEY;
  t.after(() => { if (previousWeatherKey === undefined) delete process.env.OPENWEATHER_API_KEY; else process.env.OPENWEATHER_API_KEY = previousWeatherKey; });
  process.env.CLERK_SECRET_KEY = 'fixture';
  t.mock.module('@clerk/express', { namedExports: { getAuth: (req) => ({ userId: req.headers['x-fixture-user'] || viewer, isAuthenticated: true }) } });
  const { default: trips } = await import('../src/routes/trips.js');
  const { default: activities } = await import('../src/routes/activities.js');
  const { default: share } = await import('../src/routes/share.js');
  const { default: weather } = await import('../src/routes/weather.js');
  const db = new DatabaseSync(':memory:');
  t.after(() => db.close());
  db.function('DATE_FORMAT', (value, _format) => value);
  db.function('TIME_FORMAT', (value, _format) => value);
  db.exec(`
    CREATE TABLE users (id INTEGER PRIMARY KEY, clerk_user_id TEXT, display_name TEXT);
    INSERT INTO users VALUES (1,'alice','Alice'),(2,'bob','Bob'),(3,'charlie','Charlie');
    CREATE TABLE trips (id INTEGER PRIMARY KEY, title, start_date, end_date, group_size, budget, currency_code, owner_user_id, share_token, share_enabled, time_zone TEXT, revision INTEGER NOT NULL DEFAULT 1, created_at, updated_at);
    CREATE TABLE destinations (id INTEGER PRIMARY KEY, local_name, name, country, region, category, map_query);
    INSERT INTO destinations(id, name) VALUES (1,'Hue'), (2,'Hanoi');
    CREATE TABLE trip_destinations (trip_id, destination_id, destination_order);
    CREATE TABLE trip_members (trip_id INTEGER NOT NULL, user_id INTEGER NOT NULL, PRIMARY KEY (trip_id, user_id));
    CREATE TABLE trip_invites (trip_id INTEGER PRIMARY KEY, token_hash TEXT NOT NULL, expires_at TEXT NOT NULL);
    CREATE TABLE trip_weather_location (trip_id INTEGER PRIMARY KEY, destination_id INTEGER NOT NULL, latitude REAL NOT NULL, longitude REAL NOT NULL, time_zone TEXT NOT NULL);
    CREATE TABLE activities (id INTEGER PRIMARY KEY, trip_id, activity_date, start_time, duration_minutes, version INTEGER NOT NULL DEFAULT 1, category, title, city, address, planned_cost, actual_spend, note, visited);
    CREATE TABLE trip_photos (trip_id, cloudinary_public_id);
  `);
  let failNextBump = false;
  const execute = async (sql, args) => {
    if (failNextBump && sql.startsWith('UPDATE trips SET revision = revision + 1')) { failNextBump = false; throw new Error('fixture revision failure'); }
    const stmt = db.prepare(sql.replace(/ FOR UPDATE$/, ''));
    if (sql.trimStart().startsWith('SELECT')) return [stmt.all(...args)];
    const result = stmt.run(...args);
    return [{ insertId: result.lastInsertRowid, affectedRows: Number(result.changes) }];
  };
  let held = false;
  let memberPollStarted;
  t.mock.method(pool, 'execute', (...args) => {
    assert.equal(held, false, 'transaction tried to borrow a second connection');
    if (memberPollStarted && args[0].startsWith('SELECT t.revision') && args[1][1] === 2) { memberPollStarted(); memberPollStarted = null; }
    return execute(...args);
  });
  t.mock.method(pool, 'getConnection', async () => {
    assert.equal(held, false);
    held = true;
    return { execute, beginTransaction: () => db.exec('BEGIN'), commit: () => db.exec('COMMIT'),
      rollback: async () => db.exec('ROLLBACK'), release: () => { held = false; } };
  });
  const app = express();
  app.use(express.json(), trips, activities, share, weather);
  app.use((_error, _req, res, _next) => res.status(500).end());
  const server = app.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(() => server.close());
  const origin = 'http://127.0.0.1:' + server.address().port;
  const values = { title: 'Initial', destinationIds: [1], startDate: '2026-11-15', endDate: '2026-11-16', groupSize: 2, currencyCode: 'VND', budget: '100' };
  const currentRevision = () => db.prepare('SELECT revision FROM trips LIMIT 1').get()?.revision;
  const write = (path, method, title) => fetch(origin + path, { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...values, title, ...(method === 'PUT' ? { revision: currentRevision() } : {}) }) });
  const created = await write('/', 'POST', 'Initial');
  assert.equal(created.status, 201);
  const trip = (await created.json()).data;
  assert.equal(trip.destinations[0].name, 'Hue');
  assert.equal(trip.days.length, 2);
  assert.equal(trip.role, 'owner');
  assert.equal(trip.timeZone, null);
  assert.equal(trip.revision, 1);
  const added = await fetch(origin + '/trips/' + trip.id + '/activities', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ date: values.startDate, time: '09:00', durationMinutes: 90, category: 'other', title: 'Walk' }) });
  assert.equal(added.status, 201);
  const activity = (await added.json()).data;
  assert.equal(activity.durationMinutes, 90);
  assert.equal(activity.version, 1);
  assert.equal((await (await fetch(origin + '/' + trip.id + '/version')).json()).data.revision, 2);
  const patched = await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ durationMinutes: 45, version: 1 }) });
  const patchedData = (await patched.json()).data;
  assert.equal(patchedData.durationMinutes, 45);
  assert.equal(patchedData.version, 2);
  assert.equal((await (await fetch(origin + '/' + trip.id + '/version')).json()).data.revision, 3);
  failNextBump = true;
  const failedUpdate = await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ time: '14:00', version: 2 }) });
  assert.equal(failedUpdate.status, 500);
  const afterRollback = (await (await fetch(origin + '/' + trip.id)).json()).data;
  assert.equal(afterRollback.revision, 3);
  assert.equal(afterRollback.days[0].activities[0].time, '09:00');
  assert.equal(afterRollback.days[0].activities[0].version, 2);
  const stale = await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ time: '13:00', version: 1 }) });
  assert.equal(stale.status, 409);
  assert.equal((await stale.json()).error.code, 'ACTIVITY_CONFLICT');
  assert.equal((await (await fetch(origin + '/' + trip.id + '/version')).json()).data.revision, 3);
  assert.equal((await (await fetch(origin + '/' + trip.id)).json()).data.days[0].activities[0].time, '09:00');
  const staleDelete = await fetch(origin + '/activities/' + activity.id, { method: 'DELETE', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ version: 1 }) });
  assert.equal(staleDelete.status, 409);
  assert.equal((await staleDelete.json()).error.code, 'ACTIVITY_CONFLICT');
  const missingVersion = await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ time: '13:00' }) });
  assert.equal(missingVersion.status, 400);
  assert.equal((await missingVersion.json()).error.code, 'INVALID_VERSION');
  assert.equal((await (await fetch(origin + '/' + trip.id)).json()).data.days[0].activities[0].durationMinutes, 45);
  const path = '/' + trip.id;
  const staleTripEdit = await fetch(origin + path, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...values, title: 'Stale edit', revision: 1 }) });
  assert.equal(staleTripEdit.status, 409);
  assert.equal((await staleTripEdit.json()).error.code, 'TRIP_CONFLICT');
  assert.equal((await (await fetch(origin + path)).json()).data.title, 'Initial');
  const missingTripRevision = await fetch(origin + path, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(values) });
  assert.equal(missingTripRevision.status, 400);
  viewer = 'bob';
  assert.equal((await fetch(origin + path)).status, 404);
  assert.equal((await write(path, 'PUT', 'Other')).status, 404);
  viewer = 'alice';
  const invite = await fetch(origin + path + '/invitations', { method: 'POST' });
  assert.equal(invite.status, 201);
  const token = (await invite.json()).data.token;
  assert.match(token, /^[a-f0-9]{64}$/);
  assert.notEqual(db.prepare('SELECT token_hash FROM trip_invites').get().token_hash, token);
  viewer = 'bob';
  assert.equal((await fetch(origin + path)).status, 404);
  const accept = await fetch(origin + '/invitations/accept', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ token }) });
  assert.equal(accept.status, 200);
  assert.equal((await accept.json()).data.tripId, trip.id);
  const memberTrip = await fetch(origin + path);
  assert.equal(memberTrip.status, 200);
  assert.equal((await memberTrip.json()).data.role, 'member');
  assert.equal((await write(path, 'PUT', 'Member edit')).status, 200);
  assert.equal((await (await fetch(origin + path + '/version')).json()).data.revision, 4);
  assert.equal((await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ time: '10:00', version: 2 }) })).status, 200);
  assert.equal((await (await fetch(origin + path + '/version')).json()).data.revision, 5);
  assert.equal((await fetch(origin + path, { method: 'DELETE' })).status, 404);
  assert.equal((await fetch(origin + path + '/invitations', { method: 'POST' })).status, 404);
  assert.equal((await fetch(origin + path + '/members')).status, 404);
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/share')).status, 404);
  const memberActivity = await fetch(origin + '/trips/' + trip.id + '/activities', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ date: values.startDate, category: 'other', title: 'Member activity' }) });
  assert.equal(memberActivity.status, 201);
  const memberActivityId = (await memberActivity.json()).data.id;
  assert.equal((await (await fetch(origin + path + '/version')).json()).data.revision, 6);
  assert.equal((await fetch(origin + '/activities/' + memberActivityId, { method: 'DELETE', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ version: 1 }) })).status, 204);
  assert.equal((await (await fetch(origin + path + '/version')).json()).data.revision, 7);
  viewer = 'charlie';
  assert.equal((await fetch(origin + path)).status, 404);
  assert.equal((await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ time: '11:00', version: 2 }) })).status, 404);
  assert.equal((await fetch(origin + '/invitations/accept', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ token }) })).status, 404);
  viewer = 'alice';
  assert.equal((await (await fetch(origin + path)).json()).data.title, 'Member edit');
  assert.deepEqual((await (await fetch(origin + path + '/members')).json()).data, [{ userId: 2, displayName: 'Bob' }]);
  const revoked = (await (await fetch(origin + path + '/invitations', { method: 'POST' })).json()).data.token;
  const replacement = (await (await fetch(origin + path + '/invitations', { method: 'POST' })).json()).data.token;
  viewer = 'charlie';
  assert.equal((await fetch(origin + '/invitations/accept', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ token: revoked }) })).status, 404);
  viewer = 'alice';
  assert.equal((await fetch(origin + path + '/invitations', { method: 'DELETE' })).status, 204);
  viewer = 'charlie';
  assert.equal((await fetch(origin + '/invitations/accept', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ token: replacement }) })).status, 404);
  viewer = 'alice';
  const expired = (await (await fetch(origin + path + '/invitations', { method: 'POST' })).json()).data.token;
  db.prepare('UPDATE trip_invites SET expires_at = 0').run();
  viewer = 'charlie';
  assert.equal((await fetch(origin + '/invitations/accept', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ token: expired }) })).status, 404);
  viewer = 'alice';
  assert.equal((await fetch(origin + path + '/members/2', { method: 'DELETE' })).status, 204);
  viewer = 'bob';
  assert.equal((await fetch(origin + path)).status, 404);
  assert.equal((await fetch(origin + path + '/version')).status, 404);
  assert.equal((await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ time: '12:00', version: 3 }) })).status, 404);
  viewer = null;
  assert.equal((await fetch(origin + path)).status, 401);
  assert.equal((await fetch(origin + path + '?sync=1')).status, 401);
  assert.equal((await fetch(origin + path + '/version?sync=1')).status, 401);
  viewer = 'alice';
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/share', { method: 'POST' })).status, 201);
  assert.equal((await (await fetch(origin + path + '/version')).json()).data.revision, 8);
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/share', { method: 'DELETE' })).status, 204);
  assert.equal((await (await fetch(origin + path + '/version')).json()).data.revision, 9);
  const locationBody = { destinationId: 1, latitude: 16.46, longitude: 107.59, timeZone: 'Asia/Ho_Chi_Minh', confirmed: true };
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/weather-location', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...locationBody, destinationId: 2 }) })).status, 400);
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/weather-location', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(locationBody) })).status, 200);
  assert.equal((await (await fetch(origin + path + '/version')).json()).data.revision, 10);
  const weatherResponse = await fetch(origin + '/trips/' + trip.id + '/weather');
  assert.equal(weatherResponse.status, 200);
  assert.equal((await weatherResponse.json()).data.status, 'not-configured');
  viewer = 'charlie';
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/weather')).status, 404);
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/weather-location', { method: 'DELETE' })).status, 404);
  viewer = 'alice';
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/weather-location', { method: 'DELETE' })).status, 204);
  assert.equal((await (await fetch(origin + path + '/version')).json()).data.revision, 11);
  process.env.OPENWEATHER_API_KEY = 'fixture';
  assert.equal((await (await fetch(origin + '/trips/' + trip.id + '/weather')).json()).data.status, 'missing-location');
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/weather-location', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(locationBody) })).status, 200);
  assert.equal((await write(path, 'PUT', 'Keep destination')).status, 200);
  assert.equal(db.prepare('SELECT destination_id FROM trip_weather_location WHERE trip_id = ?').get(trip.id).destination_id, 1);
  assert.equal((await fetch(origin + path, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...values, title: 'Change destination', destinationIds: [2], revision: currentRevision() }) })).status, 200);
  assert.equal(db.prepare('SELECT destination_id FROM trip_weather_location WHERE trip_id = ?').get(trip.id), undefined);
  assert.equal((await write(path, 'PUT', 'Restore destination')).status, 200);
  assert.equal(db.prepare('SELECT destination_id FROM trip_weather_location WHERE trip_id = ?').get(trip.id), undefined);
  const zoneWrite = (body) => fetch(origin + path, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...values, revision: currentRevision(), ...body }) });
  assert.equal((await zoneWrite({ timeZone: 'Asia/Ho_Chi_Minh' })).status, 400);
  assert.equal((await zoneWrite({ timeZone: 'Invalid/Zone', timeZoneConfirmed: true })).status, 400);
  const zoned = await zoneWrite({ timeZone: 'Asia/Ho_Chi_Minh', timeZoneConfirmed: true });
  assert.equal((await zoned.json()).data.timeZone, 'Asia/Ho_Chi_Minh');
  assert.equal((await (await fetch(origin + '/')).json()).data[0].timeZone, 'Asia/Ho_Chi_Minh');
  const shared = await (await fetch(origin + '/trips/' + trip.id + '/share', { method: 'POST' })).json();
  db.prepare('UPDATE activities SET note = ?, actual_spend = ? WHERE id = ?').run('private note', 42, activity.id);
  viewer = null;
  const sharedView = (await (await fetch(origin + '/share/' + shared.data.shareToken)).json()).data;
  assert.equal('budget' in sharedView, false);
  assert.equal('currencyCode' in sharedView, false);
  assert.equal(sharedView.timeZone, 'Asia/Ho_Chi_Minh');
  const sharedActivity = sharedView.days.flatMap((day) => day.activities).find((item) => item.id === activity.id);
  assert.ok(sharedActivity);
  assert.equal('note' in sharedActivity, false);
  assert.equal('actualSpend' in sharedActivity, false);
  viewer = 'alice';
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/share', { method: 'DELETE' })).status, 204);
  viewer = null;
  assert.equal((await fetch(origin + '/share/' + shared.data.shareToken)).status, 404);
  viewer = 'alice';
  assert.equal((await fetch(origin + '/trips/' + trip.id + '/weather-location', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(locationBody) })).status, 200);
  assert.equal((await (await write(path, 'PUT', 'Legacy update')).json()).data.timeZone, 'Asia/Ho_Chi_Minh');
  assert.equal(db.prepare('SELECT destination_id FROM trip_weather_location WHERE trip_id = ?').get(trip.id).destination_id, 1);
  assert.equal((await (await zoneWrite({ destinationIds: [2] })).json()).data.timeZone, null);
  assert.equal(db.prepare('SELECT destination_id FROM trip_weather_location WHERE trip_id = ?').get(trip.id), undefined);
  assert.equal((await (await write(path, 'PUT', 'Restore')).json()).data.timeZone, null);
  const edited = await write(path, 'PUT', 'Updated');
  assert.equal((await edited.json()).data.title, 'Updated');
  assert.equal((await fetch(origin + path + '/version?wait=1&since=invalid')).status, 400);
  const revision = (await (await fetch(origin + path + '/version')).json()).data.revision;
  let syncSettled = false;
  const waiting = fetch(origin + path + '/version?sync=1&wait=1&since=' + revision)
    .then(async (response) => { syncSettled = true; return response.json(); });
  await new Promise((resolve) => setTimeout(resolve, 100));
  assert.equal(syncSettled, false, 'unchanged revision should hold the request');
  await write(path, 'PUT', 'Changed by another editor');
  const synced = await waiting;
  assert.equal(synced.data.revision, revision + 1);
  assert.equal(synced.pollAfterMs, 0);
  db.prepare('INSERT INTO trip_members (trip_id, user_id) VALUES (?, ?)').run(trip.id, 2);
  viewer = 'bob';
  const memberSnapshot = (await (await fetch(origin + path)).json()).data;
  const oldActivity = memberSnapshot.days.flatMap((day) => day.activities).find((item) => item.id === activity.id);
  const pollStarted = new Promise((resolve) => { memberPollStarted = resolve; });
  const memberWait = fetch(origin + path + '/version?sync=1&wait=1&since=' + memberSnapshot.revision, { headers: { 'x-fixture-user': 'bob' } });
  await pollStarted;
  viewer = 'alice';
  const ownerEdit = await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ title: 'Owner change', version: oldActivity.version }) });
  assert.equal(ownerEdit.status, 200);
  assert.equal((await (await memberWait).json()).data.revision, memberSnapshot.revision + 1);
  viewer = 'bob';
  const memberStale = await fetch(origin + '/activities/' + activity.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ title: 'Stale member draft', version: oldActivity.version }) });
  assert.equal(memberStale.status, 409);
  assert.equal((await memberStale.json()).error.code, 'ACTIVITY_CONFLICT');
  assert.equal((await (await fetch(origin + path)).json()).data.days.flatMap((day) => day.activities).find((item) => item.id === activity.id).title, 'Owner change');
  viewer = 'alice';
  db.prepare('DELETE FROM trip_members WHERE trip_id = ? AND user_id = ?').run(trip.id, 2);
  viewer = 'bob';
  assert.equal((await fetch(origin + path + '/version?wait=1&since=' + revision)).status, 404);
  viewer = 'alice';
  assert.equal((await fetch(origin + path, { method: 'DELETE' })).status, 204);
  assert.equal((await fetch(origin + path)).status, 404);
  assert.equal(held, false);
});
